function i18n.t(key, ...)
    local entry = messages[key]
    -- Unknown IDs remain visible for diagnostics instead of disappearing.
    local value = entry and entry[i18n.language() == "zh" and 1 or 2] or key
    if select("#", ...) == 0 then return value end
    return string.format(value, ...)
end

return i18n
