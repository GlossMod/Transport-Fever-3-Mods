-- The native settings page reads app.getUserProfile():getLanguage().code.
-- Keep our language policy separate from the game's model/cargo translations.
local i18n = {}
local language

function i18n.resolve(code)
    if type(code) ~= "string" then return "en" end
    code = code:lower():gsub("-", "_")
    return (code == "zh" or code:match("^zh_")) and "zh" or "en"
end

function i18n.refresh()
    local ok, code = pcall(function() return app.getUserProfile():getLanguage().code end)
    language = i18n.resolve(ok and code or nil)
    return language
end

function i18n.language()
    return language or i18n.refresh()
end

